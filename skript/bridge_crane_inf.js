let resizeTimer;
window.addEventListener('resize', function() {
    const activePanel = document.querySelector('.info-panel.active');
    if (!activePanel) return;

    const content = activePanel.innerHTML;
    let targetId = null;

    if (content.includes('Клещевой мостовой кран')) {
        targetId = '11';
    } else if (content.includes('Мостовой кран нового типа')) {
        targetId = '2';
    }

    if (!targetId) return;

    clearTimeout(resizeTimer);
    resizeTimer = setTimeout(function() {
        const card = document.querySelector('.product-card[data-target="' + targetId + '"]');
        if (card) card.click();
    }, 300);
});

function showModel(blockNumber, targetId) {
    document.querySelectorAll('.dwg-block-menu').forEach(block => {
        block.classList.remove('active');
    });
    const targetBlock = document.getElementById(`dwg-${blockNumber}-${targetId}`) || 
                        document.getElementById(`new-dwg-${blockNumber}-${targetId}`);
    if (targetBlock) {
        targetBlock.classList.add('active');
        targetBlock.scrollIntoView({ behavior: 'smooth', block: 'start' });
    }
}

